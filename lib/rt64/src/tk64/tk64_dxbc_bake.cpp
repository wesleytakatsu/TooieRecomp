// Build-time tool: translates a SPIR-V blob to HLSL 5.0 exactly as the Direct3D 11 backend does, compiles it to DXBC and
// writes it as C data. The backend finds it by the key of its HLSL, so shaders that take minutes to compile (RT64's
// raster ubershaders) never compile while a game starts. See docs/specs/d3d11-backend.md.
//
// Usage: tk64_dxbc_bake <input.spv> <output.c> <symbol>
//

#include <cstdio>
#include <fstream>
#include <iterator>
#include <vector>

#include "tk64_hlsl_compiler.h"
#include "tk64_shader_translator.h"

namespace tk64 {
    // The tool has no baked shaders of its own.
    const BakedShader *findBakedShader(uint64_t key) {
        return nullptr;
    }
};

int main(int argc, char *argv[]) {
    if (argc != 4) {
        fprintf(stderr, "Usage: tk64_dxbc_bake <input.spv> <output.c> <symbol>\n");
        return 1;
    }

    std::ifstream input(argv[1], std::ios::binary);
    const std::vector<char> bytes((std::istreambuf_iterator<char>(input)), std::istreambuf_iterator<char>());
    std::vector<uint32_t> words(bytes.size() / sizeof(uint32_t));
    memcpy(words.data(), bytes.data(), words.size() * sizeof(uint32_t));
    const tk64::TranslatedShader translated = tk64::translateSpirv(words.data(), words.size(), tk64::ShaderLanguage::HLSL_50);
    if (!translated.ok) {
        fprintf(stderr, "tk64_dxbc_bake: %s: translation failed: %s\n", argv[1], translated.error.c_str());
        return 1;
    }

    // The developer's shader cache is read and filled too, so a rebuild that does not change the HLSL compiles nothing.
    tk64::HLSLCompiler compiler;
    compiler.open();
    std::vector<uint8_t> dxbc;
    std::string errors;
    if (!compiler.compile(translated.source, translated.stage, dxbc, errors)) {
        fprintf(stderr, "tk64_dxbc_bake: %s: compilation failed:\n%s\n", argv[1], errors.c_str());
        return 1;
    }

    FILE *output = fopen(argv[2], "w");
    if (output == nullptr) {
        fprintf(stderr, "tk64_dxbc_bake: cannot write %s\n", argv[2]);
        return 1;
    }

    const char *symbol = argv[3];
    fprintf(output, "// Generated by tk64_dxbc_bake from %s.\n#include <stdint.h>\n", argv[1]);
    fprintf(output, "const uint64_t %sKey = 0x%016llxULL;\n", symbol, (unsigned long long)(tk64::hlslKey(translated.source, translated.stage)));
    fprintf(output, "const uint32_t %sSize = %zu;\n", symbol, dxbc.size());
    fprintf(output, "const uint8_t %sDXBC[] = {", symbol);
    for (size_t i = 0; i < dxbc.size(); i++) {
        fprintf(output, "%s0x%02x,", ((i % 24) == 0) ? "\n    " : "", dxbc[i]);
    }

    fprintf(output, "\n};\n");
    fclose(output);
    return 0;
}
