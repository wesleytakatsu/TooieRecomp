#!/usr/bin/env python3
"""Generate the map name table used by the Dev Mode warp menu.

Reads the map enum of the vendored decompilation (decomp/include/maps.h, lines such as
`MAP_C7_GGM_GLITTER_GULCH_MINE = 0xC7,`) and writes src/game/generated/map_names.gen.cpp with one
readable name per map id ("GGM Glitter Gulch Mine"). Run it again after maps.h changes.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAPS_H = ROOT / "decomp" / "include" / "maps.h"
OUT_CPP = ROOT / "src" / "game" / "generated" / "map_names.gen.cpp"

ENTRY = re.compile(r"^\s*MAP_([0-9A-F]+)_(\w+)\s*=\s*0x([0-9A-Fa-f]+)\s*,")


def readable(words: str) -> str:
    parts = words.split("_")
    out = []
    for i, part in enumerate(parts):
        # The first word is the world or kind abbreviation (GGM, IOH, CS): keep it uppercase.
        if i == 0 and len(part) <= 4:
            out.append(part)
        else:
            out.append(part.capitalize())
    return " ".join(out)


def main() -> None:
    rows = []
    for line in MAPS_H.read_text(encoding="utf-8").splitlines():
        m = ENTRY.match(line)
        if m:
            rows.append((int(m.group(3), 16), readable(m.group(2))))
    rows.sort()
    lines = [
        "/* Auto-generated by tools/generate_map_names.py from decomp/include/maps.h — do not edit. */",
        '#include "tooie_dev_warp.h"',
        "",
        "namespace {",
        "struct MapName {",
        "    int16_t map;",
        "    const char* name;",
        "};",
        "",
        "constexpr MapName kMapNames[] = {",
    ]
    lines += [f'    {{0x{value:X}, "{name}"}},' for value, name in rows]
    lines += [
        "};",
        "} // namespace",
        "",
        "const char* tooie_dev_warp::map_name(int16_t map) {",
        "    for (const MapName& entry : kMapNames) {",
        "        if (entry.map == map) {",
        "            return entry.name;",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
    ]
    OUT_CPP.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT_CPP.relative_to(ROOT)}: {len(rows)} maps")


if __name__ == "__main__":
    main()
