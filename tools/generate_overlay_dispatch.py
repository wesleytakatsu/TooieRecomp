#!/usr/bin/env python3
"""Generate overlay dispatch tables for recomp_syscall_handler (P06).

Reads:
  - metadata/overlays.table.toml  (authoritative overlay index / entrypoints)
  - RecompiledFuncs/recomp_overlays.inl  (rom_addr / size by section name)

Writes:
  - src/game/generated/overlay_dispatch.inc.h
  - src/game/generated/overlay_dispatch.gen.cpp
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

TOOIE = Path(__file__).resolve().parents[1]
META = TOOIE / "metadata" / "overlays.table.toml"
INL = TOOIE / "RecompiledFuncs" / "recomp_overlays.inl"
OUT_DIR = TOOIE / "src" / "game" / "generated"
OUT_H = OUT_DIR / "overlay_dispatch.inc.h"
OUT_CPP = OUT_DIR / "overlay_dispatch.gen.cpp"


def die(msg: str, code: int = 1) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    raise SystemExit(code)


def parse_overlays(path: Path) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    blocks = re.split(r"\n\[\[overlay\]\]", text)
    if blocks[0].lstrip().startswith("[[overlay]]"):
        blocks[0] = blocks[0].split("[[overlay]]", 1)[1]
    else:
        blocks = blocks[1:]

    overlays: list[dict] = []
    for b in blocks:
        im = re.search(r"index\s*=\s*(\d+)", b)
        if not im:
            continue
        empty = bool(re.search(r"empty\s*=\s*true", b))
        nm = re.search(r'name\s*=\s*"([^"]+)"', b)
        eps: list[str] = []
        em = re.search(r"entrypoints\s*=\s*\[(.*?)\]", b, re.S)
        if em:
            eps = re.findall(r'"([^"]+)"', em.group(1))
        overlays.append(
            {
                "index": int(im.group(1)),
                "empty": empty,
                "name": nm.group(1) if nm else None,
                "entrypoints": eps,
            }
        )
    if not overlays:
        die(f"no overlays parsed from {path}")
    return overlays


def parse_section_rom_sizes(path: Path) -> dict[str, tuple[int, int]]:
    inl = path.read_text(encoding="utf-8")
    m = re.search(r"static SectionTableEntry section_table\[\] = \{(.*?)\n\};", inl, re.S)
    if not m:
        die(f"section_table not found in {path}")
    byname: dict[str, tuple[int, int]] = {}
    for em in re.finditer(
        r"\.rom_addr\s*=\s*(0x[0-9A-Fa-f]+)\s*,\s*\.ram_addr\s*=\s*(0x[0-9A-Fa-f]+)\s*,"
        r"\s*\.size\s*=\s*(0x[0-9A-Fa-f]+).*?\.funcs\s*=\s*section_\d+_(\w+)_funcs",
        m.group(1),
        re.S,
    ):
        byname[em.group(4)] = (int(em.group(1), 16), int(em.group(3), 16))
    if not byname:
        die("no sections parsed from recomp_overlays.inl")
    return byname


def main() -> None:
    if not META.is_file():
        die(f"missing {META}")
    if not INL.is_file():
        die(f"missing {INL} (run N64Recomp first)")

    overlays = parse_overlays(META)
    byname = parse_section_rom_sizes(INL)
    by_index = {o["index"]: o for o in overlays}
    max_index = max(by_index)

    missing = [
        (o["index"], o["name"])
        for o in overlays
        if not o["empty"] and o["name"] and o["name"] not in byname
    ]
    if missing:
        die(f"{len(missing)} overlays missing from section_table (e.g. {missing[:5]})")

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    OUT_H.write_text(
        "/* Auto-generated by tools/generate_overlay_dispatch.py — do not edit. */\n"
        "#pragma once\n"
        "#include <cstdint>\n"
        '#include "recomp.h"\n\n'
        "struct TooieOverlayDispatchEntry {\n"
        "    uint32_t rom_addr;\n"
        "    uint32_t size;\n"
        "    uint16_t num_entrypoints;\n"
        "    recomp_func_t* const* entrypoints; // nullptr if empty/unknown\n"
        "};\n\n"
        f"static constexpr uint32_t kTooieOverlayCount = {max_index};\n"
        "// Indexed by overlay index (1..kTooieOverlayCount). Slot 0 unused.\n"
        "extern const TooieOverlayDispatchEntry g_tooie_overlay_dispatch[kTooieOverlayCount + 1];\n",
        encoding="utf-8",
    )

    lines: list[str] = [
        "/* Auto-generated by tools/generate_overlay_dispatch.py — do not edit. */",
        '#include "overlay_dispatch.inc.h"',
        '#include "funcs.h"',
        "",
    ]

    for o in overlays:
        if o["empty"] or not o["entrypoints"]:
            continue
        idx = o["index"]
        lines.append(f"static recomp_func_t* const ovl_{idx}_entrypoints[] = {{")
        for ep in o["entrypoints"]:
            lines.append(f"    {ep},")
        lines.append("};")
        lines.append("")

    lines.append(f"const TooieOverlayDispatchEntry g_tooie_overlay_dispatch[{max_index + 1}] = {{")
    for i in range(max_index + 1):
        if i == 0 or i not in by_index:
            lines.append("    { 0, 0, 0, nullptr },")
            continue
        o = by_index[i]
        if o["empty"] or not o["name"] or not o["entrypoints"]:
            lines.append(f"    {{ 0, 0, 0, nullptr }}, // empty overlay {i}")
            continue
        rom, size = byname[o["name"]]
        n = len(o["entrypoints"])
        lines.append(
            f"    {{ 0x{rom:08X}, 0x{size:08X}, {n}, ovl_{i}_entrypoints }}, // {o['name']}"
        )
    lines.append("};")
    lines.append("")

    OUT_CPP.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_H.relative_to(TOOIE)}")
    print(f"wrote {OUT_CPP.relative_to(TOOIE)} ({OUT_CPP.stat().st_size} bytes)")
    print(
        f"overlays={len(overlays)} max_index={max_index} "
        f"entrypoints={sum(len(o['entrypoints']) for o in overlays)}"
    )


if __name__ == "__main__":
    main()
