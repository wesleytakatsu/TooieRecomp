#!/usr/bin/env python3
"""Generate N64Recomp metadata for Banjo-Tooie from the decomp ELF and maps.

MAINTAINER-ONLY: needs the ELF built by the legacy-compiler-kit decomp stage (`tools/build_linux.sh decomp`, TOOIE_TOOLCHAIN_KIT).
The normal build never runs it: it consumes the committed output (metadata/tooie.us.syms.toml) through N64Recomp's symbols_file_path.

Sources (single authority, not hand-maintained duplicates):
  - banjo-tooie-Recomp/build/us/banjotooie_decompressed.elf
  - banjo-tooie-Recomp/overlays.us.toml
  - banjo-tooie-Recomp/syscall_symbol_addrs.us.txt
  - banjo-tooie-Recomp/decompressed.us.z64

Outputs (ordered, deterministic) under TooieRecomp/metadata/.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path
from typing import Any

from tooie_paths import DECOMP as BT, N64RECOMP, TOOIE

def _rel(p: Path) -> str:
    try:
        return str(p.relative_to(TOOIE))
    except ValueError:
        return str(p)


ROOT = TOOIE
META = TOOIE / "metadata"

ELF = BT / "build" / "us" / "banjotooie_decompressed.elf"
ROM = BT / "decompressed.us.z64"
OVERLAYS_SRC = BT / "overlays.us.toml"
SYSCALLS_SRC = BT / "syscall_symbol_addrs.us.txt"

EXPECTED_ROM_SHA1 = "af479771ff5e91ce3732f3d84146614ab71d8d79"
ENTRYPOINT = 0x80000400
BSS_SUFFIX = "_bss"
OVERLAY_VRAM = 0x80800000

# Reloc types N64Recomp dump emits (R_MIPS_32 data/jump-table relocs are kept by the patched dump: the runtime overlay relocation tables need them)
KNOWN_RELOC_TYPES = frozenset({"R_MIPS_HI16", "R_MIPS_LO16", "R_MIPS_26", "R_MIPS_32"})


def die(msg: str, code: int = 1) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    raise SystemExit(code)


def sha1_file(path: Path) -> str:
    h = hashlib.sha1()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def run_readelf_sections(elf: Path) -> list[dict[str, Any]]:
    # -W (wide) is required: without it readelf truncates long section names
    # to "Name[...]". Truncated names never match N64Recomp's ELF section names,
    # so those sections are not marked relocatable and lose their relocations.
    out = subprocess.check_output(
        ["mips-linux-gnu-readelf", "-W", "-S", str(elf)],
        text=True,
        errors="replace",
    )
    sections: list[dict[str, Any]] = []
    # Example:  [ 3] .boot  PROGBITS  80000400 020400 0040e0 00 WAX  0   0 32
    pat = re.compile(
        r"\[\s*(?P<idx>\d+)\]\s+"
        r"(?P<name>\S+)\s+"
        r"(?P<type>\S+)\s+"
        r"(?P<addr>[0-9a-fA-F]+)\s+"
        r"(?P<off>[0-9a-fA-F]+)\s+"
        r"(?P<size>[0-9a-fA-F]+)\s+"
        r"(?P<es>\S+)\s+"
        r"(?P<flg>\S+)"
    )
    for line in out.splitlines():
        m = pat.search(line)
        if not m:
            continue
        sections.append(
            {
                "index": int(m.group("idx")),
                "name": m.group("name"),
                "type": m.group("type"),
                "addr": int(m.group("addr"), 16),
                "offset": int(m.group("off"), 16),
                "size": int(m.group("size"), 16),
                "flags": m.group("flg"),
            }
        )
    if not sections:
        die("failed to parse readelf -S output")
    return sections


def write_relocatable_sections(sections: list[dict[str, Any]], path: Path) -> list[str]:
    """Overlay code banks share VRAM 0x80800000 — mark as relocatable for N64Recomp."""
    names = sorted(
        {
            s["name"]
            for s in sections
            if "X" in s["flags"]
            and s["addr"] == OVERLAY_VRAM
            and s["name"].startswith(".")
        }
    )
    # Write both the ELF-derived list and the ".recomp.txt" twin consumed by
    # tooie.us.rev0.recomp.toml, keeping them identical by construction.
    recomp_twin = path.with_name(path.name.replace(".txt", ".recomp.txt"))
    for p in (path, recomp_twin):
        p.write_text("\n".join(names) + ("\n" if names else ""), encoding="utf-8")
    return names


