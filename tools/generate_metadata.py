def run_n64recomp_dump(config: Path, workdir: Path) -> tuple[Path, Path]:
    if not N64RECOMP.is_file():
        die(f"N64Recomp binary missing: {N64RECOMP} (build it in P01)")
    dump = workdir / "dump.toml"
    data_dump = workdir / "data_dump.toml"
    for p in (dump, data_dump):
        if p.exists():
            p.unlink()
    cmd = [str(N64RECOMP), str(config), "--dump-context"]
    print("Running:", " ".join(cmd), "cwd=", workdir)
    proc = subprocess.run(cmd, cwd=workdir, capture_output=True, text=True)
    if proc.returncode != 0:
        print(proc.stdout)
        print(proc.stderr, file=sys.stderr)
        die(f"N64Recomp --dump-context failed with {proc.returncode}")
    print(proc.stdout)
    if not dump.is_file() or not data_dump.is_file():
        die("N64Recomp did not write dump.toml / data_dump.toml")
    return dump, data_dump


_RELOC_LINE = re.compile(
    r'\{\s*type\s*=\s*"(?P<type>[^"]+)"\s*,\s*vram\s*=\s*0x(?P<vram>[0-9A-Fa-f]+)'
)


def validate_relocs_in_syms(syms_path: Path) -> dict[str, int]:
    """Fail if dump emits reloc types outside the known N64Recomp set."""
    counts: dict[str, int] = {}
    unknown: list[str] = []
    for line in syms_path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = _RELOC_LINE.search(line)
        if not m:
            continue
        t = m.group("type")
        counts[t] = counts.get(t, 0) + 1
        if t not in KNOWN_RELOC_TYPES:
            unknown.append(t)
    if unknown:
        die(f"unknown reloc types in dump (must fail closed): {sorted(set(unknown))}")
    return counts


def parse_overlays_toml(path: Path) -> list[dict[str, Any]]:
    """Minimal parser for overlays.us.toml [[overlay]] blocks (order-preserving)."""
    text = path.read_text(encoding="utf-8")
    overlays: list[dict[str, Any]] = []
    # Find every [[overlay]] occurrence (including at file start).
    matches = list(re.finditer(r"\[\[overlay\]\]", text))
    if not matches:
        die(f"no [[overlay]] blocks in {path}")
    for i, m in enumerate(matches):
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        block = text[start:end]
        empty = bool(re.search(r"empty\s*=\s*true", block))
        name_m = re.search(r'name\s*=\s*"([^"]+)"', block)
        name = name_m.group(1) if name_m else None
        entrypoints: list[str] = []
        em = re.search(r"entrypoints\s*=\s*\[(.*?)\]", block, re.S)
        if em:
            entrypoints = re.findall(r'"([^"]+)"', em.group(1))
        # Prefer explicit comment index "# Overlay N" when present.
        idx_m = re.search(r"#\s*Overlay\s+(\d+)", block)
        index = int(idx_m.group(1)) if idx_m else (i + 1)
        overlays.append(
            {
                "index": index,
                "empty": empty,
                "name": name,
                "entrypoints": entrypoints,
            }
        )
    # Ensure strictly increasing contiguous indices 1..N after sort by index.
    overlays.sort(key=lambda o: o["index"])
    expected = list(range(1, len(overlays) + 1))
    got = [o["index"] for o in overlays]
    if got != expected:
        die(
            f"overlay indices not contiguous 1..N: first mismatch near {got[:5]}... vs {expected[:5]}..."
        )
    return overlays


def write_overlays_table(overlays: list[dict[str, Any]], path: Path) -> None:
    """Stable JSON/TOML-ish table preserving index order including empty slots."""
    lines = [
        "# Generated from banjo-tooie-Recomp/overlays.us.toml — index order is authoritative.",
        f"# count={len(overlays)} empty={sum(1 for o in overlays if o['empty'])}",
        "",
    ]
    for o in overlays:
        lines.append("[[overlay]]")
        lines.append(f"index = {o['index']}")
        if o["empty"]:
            lines.append("empty = true")
        else:
            lines.append(f'name = "{o["name"]}"')
            lines.append("entrypoints = [")
            for e in o["entrypoints"]:
                lines.append(f'  "{e}",')
            lines.append("]")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def parse_syscalls(path: Path) -> list[dict[str, str]]:
    """Parse syscall_symbol_addrs.us.txt into ordered records."""
    rows: list[dict[str, str]] = []
    line_re = re.compile(r"^(?P<name>[A-Za-z0-9_]+)\s*=\s*(?P<addr>0x[0-9A-Fa-f]+)\s*;")
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("//"):
            continue
        m = line_re.match(line)
        if not m:
            continue
        rows.append({"name": m.group("name"), "vram": m.group("addr")})
    return rows


def write_syscalls_table(rows: list[dict[str, str]], path: Path) -> None:
    lines = [
        "# Generated from banjo-tooie-Recomp/syscall_symbol_addrs.us.txt",
        f"# count={len(rows)}",
        "",
        "[[syscalls]]",
    ]
    # Use a single array for stable snapshot
    lines.append("entries = [")
    for r in rows:
        lines.append(f'  {{ name = "{r["name"]}", vram = {r["vram"]} }},')
    lines.append("]")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def write_section_table(sections: list[dict[str, Any]], path: Path) -> None:
    lines = [
        "# ELF section table (executable + bss of interest)",
        f"# source={_rel(ELF)}",
        "",
    ]
    lines.append("[[sections]]")
    lines.append("entries = [")
    for s in sections:
        if s["type"] not in ("PROGBITS", "NOBITS") and "X" not in s["flags"]:
            continue
        if s["size"] == 0 and "X" not in s["flags"]:
            continue
        # keep PROGBITS with X or large data, and NOBITS bss
        if (
            "X" not in s["flags"]
            and not s["name"].endswith(BSS_SUFFIX)
            and s["name"]
            not in (
                ".header",
                ".ipl3",
                ".assets",
                ".overlay_table",
                ".table_addr",
                ".build_data",
            )
        ):
            # still list NOBITS *_bss and known segments
            if s["type"] != "NOBITS":
                continue
        lines.append(
            '  {{ name = "{name}", vram = 0x{addr:08X}, size = 0x{size:X}, '
            'flags = "{flags}", type = "{typ}" }},'.format(
                name=s["name"],
                addr=s["addr"],
                size=s["size"],
                flags=s["flags"],
                typ=s["type"],
            )
        )
    lines.append("]")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def coverage_report(
    sections: list[dict[str, Any]],
    reloc_names: list[str],
    syms_path: Path,
    reloc_counts: dict[str, int],
    overlays: list[dict[str, Any]],
    syscalls: list[dict[str, str]],
    path: Path,
) -> None:
    exec_secs = [s for s in sections if "X" in s["flags"] and s["size"] > 0]
    exec_bytes = sum(s["size"] for s in exec_secs)
    # Count functions in syms dump
    func_count = len(
        re.findall(r"\{\s*name\s*=", syms_path.read_text(encoding="utf-8"))
    )
    # crude: only functions = lines with size =
    func_count = len(
        re.findall(r"size\s*=\s*0x", syms_path.read_text(encoding="utf-8"))
    )
    text = f"""# P03 coverage report

Generated by `TooieRecomp/tools/generate_metadata.py`.

## Inputs

| Artifact | SHA-1 |
| --- | --- |
| `{_rel(ELF)}` | `{sha1_file(ELF)}` |
| `{_rel(ROM)}` | `{sha1_file(ROM)}` |

## Executable sections

| Metric | Value |
| --- | --- |
| Executable sections (X flag) | {len(exec_secs)} |
| Executable bytes (sum of sizes) | {exec_bytes} (0x{exec_bytes:X}) |
| Relocatable overlay sections (VRAM 0x80800000) | {len(reloc_names)} |
| Functions emitted in tooie.us.syms.toml | {func_count} |

## Relocations (from dump)

| Type | Count |
| --- | --- |
"""
    for t in sorted(reloc_counts):
        text += f"| `{t}` | {reloc_counts[t]} |\n"
    if not reloc_counts:
        text += "| _(none)_ | 0 |\n"
    text += f"""
Unknown reloc types: **0** (fail-closed validator).

## Overlays

| Metric | Value |
| --- | --- |
| Overlay table slots | {len(overlays)} |
| Empty slots | {sum(1 for o in overlays if o["empty"])} |
| Named overlays | {sum(1 for o in overlays if not o["empty"])} |
| Entrypoint symbols listed | {sum(len(o["entrypoints"]) for o in overlays)} |

## Syscalls

| Metric | Value |
| --- | --- |
| Syscall table entries | {len(syscalls)} |

## Gaps / follow-ups (P04)

- Recompilation may still need patch stubs (libultra duplicates, RSP microcodes).
- Overlay runtime registration is separate from this metadata dump.
- Coverage is **classification of ELF sections + dump acceptance**, not yet per-byte instruction classification of N64Recomp output.
"""
    path.write_text(text, encoding="utf-8")


def write_manifest(path: Path, extra: dict[str, Any]) -> None:
    data = OrderedDict()
    data["generator"] = "TooieRecomp/tools/generate_metadata.py"
    data["entrypoint"] = f"0x{ENTRYPOINT:08X}"
    data["bss_section_suffix"] = BSS_SUFFIX
    data["expected_rom_sha1"] = EXPECTED_ROM_SHA1
    data["rom_sha1"] = sha1_file(ROM)
    data["elf_sha1"] = sha1_file(ELF)
    data.update(extra)
    path.write_text(
        json.dumps(data, indent=2, sort_keys=False) + "\n", encoding="utf-8"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--skip-dump",
        action="store_true",
        help="Reuse existing dump.toml if present (debug only)",
    )
    args = parser.parse_args()

    META.mkdir(parents=True, exist_ok=True)
    if not ELF.is_file():
        die(f"missing ELF (run P02 first): {ELF}")
    if not ROM.is_file():
        die(f"missing decompressed ROM: {ROM}")
    rom_sha = sha1_file(ROM)
    if rom_sha != EXPECTED_ROM_SHA1:
        die(f"ROM SHA-1 {rom_sha} != {EXPECTED_ROM_SHA1}")

    sections = run_readelf_sections(ELF)
    reloc_names = write_relocatable_sections(
        sections, META / "relocatable_sections.txt"
    )
    write_section_table(sections, META / "section_table.toml")

    write_dump_config(
        TOOIE / "tooie.us.rev0.dump.toml", META / "relocatable_sections.txt"
    )
    write_recomp_config(TOOIE / "tooie.us.rev0.toml")

    dump_src = TOOIE / "dump.toml"
    data_src = TOOIE / "data_dump.toml"
    if args.skip_dump and dump_src.is_file() and data_src.is_file():
        print("Reusing existing dump.toml / data_dump.toml")
    else:
        dump_src, data_src = run_n64recomp_dump(
            TOOIE / "tooie.us.rev0.dump.toml", TOOIE
        )

    # Stable output names
    syms = META / "tooie.us.syms.toml"
    datasyms = META / "tooie.us.datasyms.toml"
    shutil.copyfile(dump_src, syms)
    shutil.copyfile(data_src, datasyms)
    # The function dump IS tooie.us.syms.toml (no second 10 MB copy is kept); the data dump raw copy stays for debugging.
    dump_src.unlink()
    data_src.replace(META / "n64recomp_data_dump.raw.toml")

    reloc_counts = validate_relocs_in_syms(syms)

    overlays = parse_overlays_toml(OVERLAYS_SRC)
    write_overlays_table(overlays, META / "overlays.table.toml")

    syscalls = parse_syscalls(SYSCALLS_SRC)
    write_syscalls_table(syscalls, META / "syscalls.table.toml")

    coverage_report(
        sections,
        reloc_names,
        syms,
        reloc_counts,
        overlays,
        syscalls,
        META / "coverage_report.md",
    )

    write_manifest(
        META / "manifest.json",
        {
            "relocatable_sections": len(reloc_names),
            "overlays": len(overlays),
            "empty_overlays": sum(1 for o in overlays if o["empty"]),
            "syscalls": len(syscalls),
            "reloc_type_counts": reloc_counts,
            "syms_sha256": hashlib.sha256(syms.read_bytes()).hexdigest(),
            "datasyms_sha256": hashlib.sha256(datasyms.read_bytes()).hexdigest(),
        },
    )

    print("Wrote metadata to", META)
    print("  relocatable sections:", len(reloc_names))
    print(
        "  overlays:", len(overlays), "empty:", sum(1 for o in overlays if o["empty"])
    )
    print("  syscalls:", len(syscalls))
    print("  reloc types:", reloc_counts)


if __name__ == "__main__":
    main()
