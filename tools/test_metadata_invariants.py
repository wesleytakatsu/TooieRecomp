#!/usr/bin/env python3
"""Invariant and snapshot tests for TooieRecomp metadata (P03)."""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
META = ROOT / "TooieRecomp" / "metadata"
SNAP = ROOT / "TooieRecomp" / "tests" / "snapshots"

KNOWN_RELOC = frozenset({"R_MIPS_HI16", "R_MIPS_LO16", "R_MIPS_26"})


def fail(msg: str) -> None:
    print(f"FAIL: {msg}")
    raise SystemExit(1)


def ok(msg: str) -> None:
    print(f"OK: {msg}")


def main() -> None:
    required = [
        "tooie.us.syms.toml",
        "tooie.us.datasyms.toml",
        "relocatable_sections.txt",
        "overlays.table.toml",
        "syscalls.table.toml",
        "section_table.toml",
        "coverage_report.md",
        "manifest.json",
    ]
    for name in required:
        p = META / name
        if not p.is_file() or p.stat().st_size == 0:
            fail(f"missing or empty {p}")
    ok("all metadata files present")

    manifest = json.loads((META / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("expected_rom_sha1") != manifest.get("rom_sha1"):
        fail("manifest ROM SHA-1 mismatch")
    ok("ROM SHA-1 matches expected")

    syms = (META / "tooie.us.syms.toml").read_text(encoding="utf-8")
    if not syms.startswith("# Autogenerated from an ELF via N64Recomp"):
        fail("syms header missing N64Recomp autogen marker")
    if "[[section]]" not in syms:
        fail("no sections in syms")
    if "functions = [" not in syms:
        fail("no functions array in syms")
    ok("syms structure")

    # Reloc types
    types = set(re.findall(r'type\s*=\s*"([^"]+)"', syms))
    unknown = types - KNOWN_RELOC
    if unknown:
        fail(f"unknown reloc types: {unknown}")
    ok(f"reloc types subset of known: {sorted(types)}")

    # Relocatable list non-empty, sorted unique
    reloc_lines = [
        ln.strip()
        for ln in (META / "relocatable_sections.txt")
        .read_text(encoding="utf-8")
        .splitlines()
        if ln.strip()
    ]
    if not reloc_lines:
        fail("relocatable_sections empty")
    if reloc_lines != sorted(reloc_lines):
        fail("relocatable_sections not sorted")
    if len(reloc_lines) != len(set(reloc_lines)):
        fail("relocatable_sections has duplicates")
    ok(f"relocatable_sections ordered unique ({len(reloc_lines)})")

    # Every listed section must be a real ELF section, and the list must be
    # EXACTLY the generator's relocatable-overlay policy set. This is a
    # semantic equality check (not just existence): a missing section silently
    # drops relocations (P08 readelf-truncation regression), so the set must
    # match the ELF-derived expectation one-for-one.
    elf = ROOT / "banjo-tooie-Recomp" / "build" / "us" / "banjotooie_decompressed.elf"
    if elf.is_file():
        import subprocess

        out = subprocess.check_output(
            ["mips-linux-gnu-readelf", "-W", "-S", str(elf)],
            text=True,
            errors="replace",
        )
        elf_sections = set(re.findall(r"\[\s*\d+\]\s+(\S+)\s+\S+\s+[0-9a-fA-F]+", out))
        expected = set()
        for line in out.splitlines():
            m = re.match(
                r"\s*\[\s*\d+\]\s+(\S+)\s+(\S+)\s+([0-9a-fA-F]+)\s+"
                r"[0-9a-fA-F]+\s+[0-9a-fA-F]+\s+\S+\s+(\S+)",
                line,
            )
            if not m:
                continue
            name, typ, addr, fl = m.groups()
            if "X" in fl and int(addr, 16) == 0x80800000 and name.startswith("."):
                expected.add(name)
        actual = set(reloc_lines)
        truncated = [n for n in reloc_lines if "[...]" in n]
        if truncated:
            fail(f"relocatable_sections contains truncated names: {truncated[:3]}")
        missing = sorted(actual - elf_sections)
        if missing:
            fail(f"relocatable_sections has names not present in ELF: {missing[:3]}")
        if actual != expected:
            only = sorted(actual - expected)[:3]
            absent = sorted(expected - actual)[:3]
            fail(
                f"relocatable_sections != ELF policy set "
                f"(actual={len(actual)} expected={len(expected)}): "
                f"only_in_list={only} missing_from_list={absent}"
            )
        ok(
            f"relocatable_sections == ELF policy set "
            f"({len(reloc_lines)} executable overlay sections @0x80800000)"
        )
        recomp_lines = [
            ln.strip()
            for ln in (META / "relocatable_sections.recomp.txt")
            .read_text(encoding="utf-8")
            .splitlines()
            if ln.strip()
        ]
        if recomp_lines != reloc_lines:
            fail(
                "relocatable_sections.recomp.txt diverges from relocatable_sections.txt"
            )
        ok("relocatable_sections.recomp.txt in sync")
    else:
        print("NOTE: ELF missing; skipped name cross-check")

    # Overlays preserve empty slots and monotonic index
    ov = (META / "overlays.table.toml").read_text(encoding="utf-8")
    indices = [int(x) for x in re.findall(r"^index = (\d+)", ov, re.M)]
    if not indices:
        fail("no overlay indices")
    if indices != list(range(1, len(indices) + 1)):
        fail("overlay indices not contiguous starting at 1")
    empty_n = ov.count("empty = true")
    if empty_n < 1:
        fail("expected some empty overlay slots")
    ok(f"overlays indices 1..{len(indices)} empty={empty_n}")

    # Syscalls non-empty
    sc = (META / "syscalls.table.toml").read_text(encoding="utf-8")
    if "entries = [" not in sc:
        fail("syscalls entries missing")
    sc_count = len(re.findall(r"name\s*=", sc))
    if sc_count < 100:
        fail(f"suspiciously few syscalls: {sc_count}")
    ok(f"syscalls entries={sc_count}")

    # Snapshot: stable hashes of key structural extracts (not full multi-MB dump)
    SNAP.mkdir(parents=True, exist_ok=True)
    snapshot = {
        "reloc_section_count": len(reloc_lines),
        "overlay_count": len(indices),
        "empty_overlays": empty_n,
        "syscall_count": sc_count,
        "syms_sha256": hashlib.sha256(
            (META / "tooie.us.syms.toml").read_bytes()
        ).hexdigest(),
        "datasyms_sha256": hashlib.sha256(
            (META / "tooie.us.datasyms.toml").read_bytes()
        ).hexdigest(),
        "reloc_list_sha256": hashlib.sha256(
            (META / "relocatable_sections.txt").read_bytes()
        ).hexdigest(),
        "overlays_table_sha256": hashlib.sha256(
            (META / "overlays.table.toml").read_bytes()
        ).hexdigest(),
        "syscalls_table_sha256": hashlib.sha256(
            (META / "syscalls.table.toml").read_bytes()
        ).hexdigest(),
    }
    snap_path = SNAP / "metadata_snapshot.json"
    write_snap = "--write-snapshot" in sys.argv
    if write_snap or not snap_path.is_file():
        snap_path.write_text(json.dumps(snapshot, indent=2) + "\n", encoding="utf-8")
        ok(f"wrote snapshot {snap_path}")
    else:
        prev = json.loads(snap_path.read_text(encoding="utf-8"))
        for key in (
            "reloc_section_count",
            "overlay_count",
            "empty_overlays",
            "syscall_count",
        ):
            if prev.get(key) != snapshot[key]:
                fail(f"snapshot drift on {key}: {prev.get(key)} -> {snapshot[key]}")
        ok("snapshot counts match previous")
        if prev.get("syms_sha256") != snapshot["syms_sha256"]:
            print(
                "NOTE: syms sha256 changed vs snapshot (tool/dump churn); counts still match"
            )

    print("PASS: metadata invariants")


if __name__ == "__main__":
    main()
